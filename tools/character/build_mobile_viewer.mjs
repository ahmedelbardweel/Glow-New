import { build } from 'esbuild';
import { copyFile, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
await build({
  entryPoints: [new URL('./mobile_viewer.mjs', import.meta.url).pathname.replace(/^\/(\w:)/, '$1')],
  bundle: true, minify: true, format: 'iife', target: ['safari16', 'chrome110'],
  outfile: new URL('../../assets/3d/character_mobile.js', import.meta.url).pathname.replace(/^\/(\w:)/, '$1'),
  legalComments: 'eof',
});
await copyFile(new URL('./node_modules/three/LICENSE', import.meta.url), new URL('../../assets/3d/three-LICENSE.txt', import.meta.url));
// Content version, not file length: equal-size model edits must reach installed phones.
const hash = createHash('sha256');
for (const name of ['character_mobile.html', 'character_mobile.js', 'glow_rigged.glb', 'glow_mascot.glb']) {
  hash.update(name).update(await readFile(new URL('../../assets/3d/' + name, import.meta.url)));
}
await writeFile(new URL('../../lib/core/services/character_pack_version.dart', import.meta.url),
  `// Generated by tools/character/build_mobile_viewer.mjs.\nconst characterPackVersion = '${hash.digest('hex')}';\n`);
