function parseScriptLines(script) {
  const charMap = {
    'بورت': 'port',
    'فورت': 'fort',
    'مورت': 'mort',
    'سورت': 'sort',
    'كورت': 'qort',
    'لورت': 'lort'
  };

  const lines = [];
  for (const raw of script.split('\n')) {
    const trimmed = raw.trim();
    if (!trimmed) continue;
    const slashIdx = trimmed.lastIndexOf('/');
    if (slashIdx === -1) {
      lines.push({ text: trimmed, characterId: 'port' });
      continue;
    }
    const text = trimmed.slice(0, slashIdx).trim();
    const tag = trimmed.slice(slashIdx + 1).trim();
    const cleanTag = tag.replace(/^[.،,!؟:\s]+|[.،,!؟:\s]+$/g, '');
    const charId = charMap[cleanTag] || 'port';
    lines.push({ text, characterId: charId });
  }
  return lines;
}

function buildTimeline(lines) {
  const blocks = [];
  const motionBlocks = [];
  const transitions = [];
  let currentTime = 0.0;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    // Estimate speech duration: ~10 chars per second + pause
    const cleanLen = line.text.replace(/[\u064B-\u065F\s]/g, '').length;
    const duration = Math.max(1.8, Math.round((cleanLen * 0.12 + 0.6) * 10) / 10);
    const start = Math.round(currentTime * 100) / 100;
    const end = Math.round((currentTime + duration) * 100) / 100;

    blocks.push({
      characterId: line.characterId,
      startTime: start,
      endTime: end
    });

    // Determine motion based on character and words
    let motionId = 'talk';
    const text = line.text;
    if (text.includes('متحمس') || text.includes('حماس') || text.includes('قَفَزَ')) {
      motionId = 'excited';
    } else if (text.includes('فخور') || text.includes('فَخْرٍ') || text.includes('بَرَافُو')) {
      motionId = 'winCelebration';
    } else if (text.includes('ابْتَسَمَ') || text.includes('ابْتَسَمْتُ') || text.includes('أَثِقُ بِكَ')) {
      motionId = 'smile';
    } else if (text.includes('ضَحِكَ') || text.includes('ضَاحِكًا')) {
      motionId = 'laugh';
    } else if (text.includes('تَذَكَّرْ') || text.includes('حِكْمَة') || text.includes('تَفْكِير')) {
      motionId = 'thinking';
    } else if (text.includes('خَائِف') || text.includes('تَجَمَّدْتُ') || text.includes('يَخْفِقُ')) {
      motionId = 'nervous';
    } else if (text.includes('مُحْتَار') || text.includes('أَيَّ طَرِيقٍ')) {
      motionId = 'confused';
    } else if (text.includes('شَجَّعَ') || text.includes('أَحْسَنْتَ') || text.includes('هَيَّا')) {
      motionId = 'encourage';
    }

    motionBlocks.push({
      motionId: motionId,
      startTime: start,
      endTime: end
    });

    if (i > 0 && lines[i].characterId !== lines[i - 1].characterId) {
      transitions.push({
        time: start,
        duration: 0.5,
        type: i % 2 === 0 ? 'slide' : 'pop'
      });
    }

    currentTime = end;
  }

  return {
    blocks,
    motionBlocks,
    hatBlocks: [],
    glassesBlocks: [],
    musclesBlocks: [],
    jumpBlocks: [],
    transitions,
    totalDuration: Math.round(currentTime * 100) / 100
  };
}

